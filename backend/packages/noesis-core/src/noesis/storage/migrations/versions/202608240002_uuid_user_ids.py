    _collect_legacy_ids()

    # Keep the JSON copy used by older chat code consistent with the new ID.
    op.execute(
        sa.text(
            """
            UPDATE t_chat_session AS s
            SET extra = jsonb_set(
                s.extra::jsonb,
                '{user_id}',
                to_jsonb(mapping.user_uuid::text),
                false
            )
            FROM _noesis_user_id_map AS mapping
            WHERE jsonb_typeof(s.extra::jsonb) = 'object'
              AND s.extra::jsonb ? 'user_id'
              AND mapping.legacy_user_id = s.extra::jsonb->>'user_id'
            """
        )
    )

