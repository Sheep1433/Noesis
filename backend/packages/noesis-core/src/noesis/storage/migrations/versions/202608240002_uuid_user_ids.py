def _collect_legacy_ids() -> None:
    op.execute(
        sa.text(
            """
            CREATE TEMP TABLE _noesis_user_id_map (
                legacy_user_id TEXT PRIMARY KEY,
                user_uuid UUID NOT NULL
            ) ON COMMIT DROP
            """
        )
    )
    op.execute(
        sa.text(
            """
            INSERT INTO _noesis_user_id_map (legacy_user_id, user_uuid)
            SELECT id::text, md5('noesis-user:' || id::text)::uuid
            FROM t_user
            ON CONFLICT (legacy_user_id) DO NOTHING
            """
        )
    )
    for table in _STRING_USER_TABLES:
        op.execute(
            sa.text(
                f"""
                INSERT INTO _noesis_user_id_map (legacy_user_id, user_uuid)
                SELECT DISTINCT user_id::text, md5('noesis-user:' || user_id::text)::uuid
                FROM {table}
                WHERE user_id IS NOT NULL
                ON CONFLICT (legacy_user_id) DO NOTHING
                """
            )
        )
    # The seeded admin is the only user created by the legacy bootstrap.
    # Give it a real UUIDv7 instead of keeping the compatibility UUID derived
    # from the old integer primary key.
    op.execute(
        sa.text(
            """
            UPDATE _noesis_user_id_map AS mapping
            SET user_uuid = CAST(:admin_uuid AS uuid)
            FROM t_user AS user_row
            WHERE user_row.username = 'admin'
              AND mapping.legacy_user_id = user_row.id::text
            """
        ).bindparams(admin_uuid=new_uuid7())
    )


def _convert_t_user() -> None:
    op.execute(
        sa.text(
            """
            ALTER TABLE t_user ADD COLUMN __noesis_user_uuid UUID
            """
        )
    )
    op.execute(
        sa.text(
            """
            UPDATE t_user AS u
            SET __noesis_user_uuid = m.user_uuid
            FROM _noesis_user_id_map AS m
            WHERE m.legacy_user_id = u.id::text
            """
        )
    )
    op.execute(sa.text("ALTER TABLE t_user DROP CONSTRAINT t_user_pkey"))
    op.execute(sa.text("ALTER TABLE t_user DROP COLUMN id"))
    op.execute(sa.text("ALTER TABLE t_user RENAME COLUMN __noesis_user_uuid TO id"))
    op.execute(sa.text("ALTER TABLE t_user ADD CONSTRAINT t_user_pkey PRIMARY KEY (id)"))


def _convert_user_id_column(table: str) -> None:
    op.execute(sa.text(f"ALTER TABLE {table} ADD COLUMN __noesis_user_uuid UUID"))
    op.execute(
        sa.text(
            f"""
            UPDATE {table} AS target
            SET __noesis_user_uuid = mapping.user_uuid
            FROM _noesis_user_id_map AS mapping
            WHERE mapping.legacy_user_id = target.user_id::text
            """
        )
    )
    op.execute(
        sa.text(
            f"""
            DO $$
            BEGIN
                IF EXISTS (SELECT 1 FROM {table} WHERE __noesis_user_uuid IS NULL) THEN
                    RAISE EXCEPTION 'cannot map legacy user_id values in {table}';
                END IF;
            END $$
            """
        )
    )
    op.execute(sa.text(f"ALTER TABLE {table} DROP COLUMN user_id"))
    op.execute(sa.text(f"ALTER TABLE {table} RENAME COLUMN __noesis_user_uuid TO user_id"))
    op.execute(sa.text(f"ALTER TABLE {table} ALTER COLUMN user_id SET NOT NULL"))


